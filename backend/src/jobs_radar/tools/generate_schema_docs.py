"""Generate ``docs/database/schema.md`` from the ORM metadata (``make docs-schema``).

Because every table and column must carry a comment (``make docs-check``), the generated document is
always a complete data dictionary.
"""

import sys
from pathlib import Path

from sqlalchemy import CheckConstraint, ForeignKeyConstraint, MetaData, Table, UniqueConstraint

SNAPSHOT_PATH = Path(__file__).resolve().parents[4] / "docs" / "database" / "schema.md"


def _constraints(table: Table) -> list[str]:
    lines: list[str] = []
    for constraint in sorted(table.constraints, key=lambda c: str(c.name)):
        if isinstance(constraint, UniqueConstraint):
            columns = ", ".join(column.name for column in constraint.columns)
            lines.append(f"- unique `{constraint.name}` ({columns})")
        elif isinstance(constraint, CheckConstraint) and constraint.name:
            lines.append(f"- check `{constraint.name}`: `{constraint.sqltext}`")
        elif isinstance(constraint, ForeignKeyConstraint):
            for element in constraint.elements:
                lines.append(f"- foreign key `{element.parent.name}` → `{element.target_fullname}`")
    return lines


def render_schema_markdown(metadata: MetaData) -> str:
    """Render every table of ``metadata`` as a Markdown data dictionary."""
    parts = [
        "# Database schema\n",
        "Generated by `make docs-schema` from the ORM models; do not edit by hand.\n",
    ]
    for table in sorted(metadata.tables.values(), key=lambda t: t.name):
        parts.append(f"\n## {table.name}\n")
        if table.comment:
            parts.append(f"\n{table.comment}\n")
        parts.append("\n| Column | Type | Nullable | Description |\n|---|---|---|---|\n")
        for column in table.columns:
            nullable = "yes" if column.nullable else "no"
            description = (column.comment or "").replace("|", "\\|")
            parts.append(f"| `{column.name}` | {column.type!s} | {nullable} | {description} |\n")
        constraints = _constraints(table)
        if constraints:
            parts.append("\n" + "\n".join(constraints) + "\n")
    return "".join(parts)


def build_schema_docs() -> str:
    """Render the documentation for the application's own metadata."""
    import jobs_radar.db.models  # noqa: F401  # registers every table on Base.metadata
    from jobs_radar.db.base import Base

    return render_schema_markdown(Base.metadata)


def main() -> int:
    """Write the documentation file."""
    SNAPSHOT_PATH.parent.mkdir(parents=True, exist_ok=True)
    SNAPSHOT_PATH.write_text(build_schema_docs())
    print(f"wrote {SNAPSHOT_PATH}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
