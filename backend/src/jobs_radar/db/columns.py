"""Column factories that keep every model short and guarantee a comment on each column (ADR-030).

Primary keys are ``BIGINT GENERATED BY DEFAULT AS IDENTITY``; foreign keys reuse the referenced
primary key name (ADR-014); enumerations are stored as text with a named CHECK constraint so that
adding a value is a simple migration.
"""

from datetime import datetime
from enum import StrEnum
from typing import Any

from sqlalchemy import (
    BigInteger,
    Boolean,
    CheckConstraint,
    DateTime,
    ForeignKey,
    Identity,
    Integer,
    LargeBinary,
    Numeric,
    String,
    Text,
    false,
    func,
    text,
    true,
)
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import MappedColumn, mapped_column


def pk_column(comment: str) -> MappedColumn[int]:
    """Surrogate primary key (identity)."""
    return mapped_column(BigInteger, Identity(always=False), primary_key=True, comment=comment)


def fk_column(
    target: str,
    comment: str,
    *,
    nullable: bool = False,
    ondelete: str = "RESTRICT",
    unique: bool = False,
    index: bool = True,
    use_alter: bool = False,
    name: str | None = None,
) -> MappedColumn[Any]:
    """Foreign key to ``target`` (``table.column``); ``use_alter`` breaks circular references."""
    constraint = ForeignKey(target, ondelete=ondelete, use_alter=use_alter, name=name)
    return mapped_column(
        BigInteger,
        constraint,
        nullable=nullable,
        unique=unique,
        index=index and not unique,
        comment=comment,
    )


def text_column(
    comment: str,
    *,
    length: int | None = None,
    nullable: bool = False,
    unique: bool = False,
    default: str | None = None,
    index: bool = False,
) -> MappedColumn[Any]:
    """Text column; ``length`` makes it ``VARCHAR(length)``, otherwise unbounded ``TEXT``."""
    return mapped_column(
        String(length) if length else Text,
        nullable=nullable,
        unique=unique,
        index=index,
        server_default=default,  # a plain str is rendered by SQLAlchemy as a quoted SQL literal
        comment=comment,
    )


def bool_column(comment: str, *, default: bool) -> MappedColumn[bool]:
    """Boolean column that is never null."""
    return mapped_column(
        Boolean, nullable=False, server_default=true() if default else false(), comment=comment
    )


def int_column(
    comment: str, *, nullable: bool = False, default: int | None = None, index: bool = False
) -> MappedColumn[Any]:
    """Integer column."""
    return mapped_column(
        Integer,
        nullable=nullable,
        index=index,
        server_default=text(str(default)) if default is not None else None,
        comment=comment,
    )


def version_column() -> MappedColumn[int]:
    """Optimistic-concurrency counter for mutable rows (ADR-030)."""
    return mapped_column(
        Integer,
        nullable=False,
        server_default=text("1"),
        comment="Optimistic-concurrency counter, incremented on every change of the row.",
    )


def numeric_column(
    comment: str, *, precision: int = 6, scale: int = 4, nullable: bool = False
) -> MappedColumn[Any]:
    """Fixed-point decimal column (confidences, similarities, contributions)."""
    return mapped_column(Numeric(precision, scale), nullable=nullable, comment=comment)


def timestamp_column(
    comment: str, *, nullable: bool = False, default_now: bool = False, index: bool = False
) -> MappedColumn[datetime]:
    """Timezone-aware UTC timestamp."""
    return mapped_column(
        DateTime(timezone=True),
        nullable=nullable,
        index=index,
        server_default=func.now() if default_now else None,
        comment=comment,
    )


def json_column(comment: str, *, nullable: bool = False) -> MappedColumn[Any]:
    """JSONB column. Content is validated by Pydantic models carrying ``schema_version``."""
    return mapped_column(JSONB, nullable=nullable, comment=comment)


def bytes_column(comment: str, *, nullable: bool = True) -> MappedColumn[bytes | None]:
    """Binary column, used only for encrypted credentials (ADR-033)."""
    return mapped_column(LargeBinary, nullable=nullable, comment=comment)


def enum_check(column: str, enum: type[StrEnum], *, nullable: bool = False) -> CheckConstraint:
    """Named CHECK limiting ``column`` to the values of ``enum`` (null allowed if ``nullable``)."""
    values = ", ".join(f"'{member.value}'" for member in enum)
    condition = f"{column} IN ({values})"
    if nullable:
        condition = f"{column} IS NULL OR {condition}"
    return CheckConstraint(condition, name=f"{column}_valid")
